/**
 * Computes feedback loop learning adjustment given predicted vs actual ground-truth outcome
 */
export function calculateOutcomeFeedback(
  predictedDays: number,
  actualDays: number,
  predictedWaste: number,
  actualWaste: number,
  supplierName: string
) {
  const errorDays = +(actualDays - predictedDays).toFixed(2);
  const deltaWaste = +(actualWaste - predictedWaste).toFixed(2);

  // If actual shelf-life was shorter than predicted (respiration faster than thought),
  // increase Q10 respiration factor. If longer, decrease Q10.
  const q10Adjustment = +(errorDays < 0 ? Math.min(0.12, Math.abs(errorDays) * 0.05) : -Math.min(0.08, errorDays * 0.03)).toFixed(3);

  // Supplier trust weighting:
  // If actual waste was higher than predicted, lower supplier trust index
  const supplierAdjustment = +(deltaWaste > 2.0 ? -1.5 : deltaWaste < -1.0 ? +1.0 : +0.2).toFixed(1);

  // Dynamic pricing elasticity correction:
  // If actual waste was higher despite discount, steepen markdown threshold
  const elasticityShift = +(deltaWaste > 2.0 ? +0.05 : -0.02).toFixed(3);

  return {
    errorDays,
    deltaWaste,
    q10Adjustment,
    supplierAdjustment,
    elasticityShift,
    decayCorrection: +(-errorDays * 0.015).toFixed(3),
  };
}
